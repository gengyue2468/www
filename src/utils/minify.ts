import { minify as minifyHtmlSource } from "html-minifier-terser";
import { transform, transformStyleAttribute } from "lightningcss";
import { minify_sync } from "terser";
import { optimize } from "svgo";
import { join } from "path";
import { AppError, ErrorCode } from "./errors.js";

/** Parse CSS instead of removing whitespace inside strings, URLs or calc(). */
export function minifyCss(source: string, filename = "site.css", inline = false): string {
  try {
    const options = { filename, code: Buffer.from(source), minify: true, errorRecovery: false };
    const result = inline ? transformStyleAttribute(options) : transform(options);
    return Buffer.from(result.code).toString();
  } catch (err) {
    throw AppError.fromError(err, ErrorCode.BUILD_ERROR, { phase: "css-minify", filename });
  }
}

/** Mangle local identifiers, never DOM properties, selectors or public APIs. */
export function minifyJavaScript(source: string, options: { module?: boolean; inline?: boolean } = {}): string {
  try {
    const result = minify_sync(source, {
      ecma: 2022,
      module: options.module ?? true,
      compress: { passes: 10, unsafe: false },
      mangle: { properties: false },
      parse: { bare_returns: options.inline === true },
      format: { comments: "some", inline_script: true },
    });
    if (result.code === undefined) throw new Error("JavaScript minifier returned no code");
    return result.code;
  } catch (err) {
    throw AppError.fromError(err, ErrorCode.BUILD_ERROR, { phase: "js-minify" });
  }
}

function prepareHtml(html: string, filename: string): { html: string; spaceGuard: string } {
  let spaceGuard = "OPENCODE_WHITESPACE_GUARD";
  while (html.includes(spaceGuard)) spaceGuard += "_";
  let content = "";
  const prepared = new HTMLRewriter().on(
    'script[type="application/ld+json"], script[type="application/json"], script[type="speculationrules"]',
    {
      element(element) {
        content = "";
        element.onEndTag(end => {
          if (!content.trim()) return;
          // JSON strings retain their spaces. Escape '<' to prevent a value
          // containing '</script>' from ending the HTML raw-text element.
          const compact = JSON.stringify(JSON.parse(content)).replaceAll("<", "\\u003c");
          end.before(compact, { html: true });
        });
      },
      text(chunk) {
        content += chunk.text;
        chunk.remove();
      },
    },
  ).on("code [style], math [style]", {
    element(element) {
      // These fragments retain exact text/markup during HTML minification,
      // but their generated ANSI/KaTeX CSS can still be safely optimized.
      const style = element.getAttribute("style");
      if (style) element.setAttribute("style", minifyCss(style, filename, true));
    },
  }).on("*", {
    element(element) {
      if (!element.tagName.includes("-")) return;
      // HTMLMinifier treats unknown tags as blocks, but custom elements can
      // be inline. Temporary text guards protect their existing boundary
      // spaces, letting us aggressively remove ordinary layout whitespace.
      element.before(spaceGuard);
      element.prepend(spaceGuard);
      element.append(spaceGuard);
      element.after(spaceGuard);
    },
  }).transform(html);
  return { html: prepared, spaceGuard };
}

export async function minifyHtml(source: string, filename = "page.html"): Promise<string> {
  try {
    const prepared = prepareHtml(source, filename);
    const result = await minifyHtmlSource(prepared.html, {
      caseSensitive: true,
      collapseWhitespace: true,
      conservativeCollapse: false,
      collapseInlineTagWhitespace: false,
      collapseBooleanAttributes: true,
      decodeEntities: true,
      removeComments: true,
      removeAttributeQuotes: true,
      removeScriptTypeAttributes: true,
      removeStyleLinkTypeAttributes: true,
      sortAttributes: true,
      sortClassName: true,
      useShortDoctype: true,
      // Empty attributes and elements are component hooks. Explicit structural
      // tags preserve tbody, custom elements and the no-script fallback tree.
      removeEmptyAttributes: false,
      removeEmptyElements: false,
      removeOptionalTags: false,
      removeRedundantAttributes: true,
      includeAutoGeneratedTags: false,
      // pre/textarea are protected by the parser; preserve inline code and
      // MathML as well, including textContent used by copying/accessibility.
      ignoreCustomFragments: [/<code(?=[\s>])[\s\S]*?<\/code>/, /<math(?=[\s>])[\s\S]*?<\/math>/],
      minifyCSS: async (text: string, type?: string) => type === "media" ? text.trim() : minifyCss(text, filename, type === "inline"),
      // Classic scripts must not lose globals that subsequent scripts use.
      minifyJS: async (text: string, inline?: boolean) => minifyJavaScript(text, { module: false, inline }),
    });
    return result.replaceAll(prepared.spaceGuard, "");
  } catch (err) {
    throw AppError.fromError(err, ErrorCode.BUILD_ERROR, { phase: "html-minify", filename });
  }
}

/** Optimize SVG structure, retaining dimensions, IDs and accessible labels. */
export function minifySvg(source: string, filename = "image.svg"): string {
  try {
    const result = optimize(source, {
      path: filename,
      multipass: true,
      floatPrecision: 6,
      js2svg: { pretty: false },
      plugins: [{
        name: "preset-default",
        params: {
          overrides: {
            cleanupIds: false,
            removeDesc: false,
            removeHiddenElems: false,
            removeUnknownsAndDefaults: { keepDataAttrs: true, keepAriaAttrs: true },
          },
        },
      }],
    });
    return Buffer.byteLength(result.data) < Buffer.byteLength(source) ? result.data : source;
  } catch (err) {
    throw AppError.fromError(err, ErrorCode.BUILD_ERROR, { phase: "svg-minify", filename });
  }
}

/** SVGs use their existing public URLs; never overwrite the source files. */
export async function minifySvgFiles(publicDir: string, outputDir: string): Promise<MinificationStats> {
  const stats = { files: 0, bytesBefore: 0, bytesAfter: 0 };
  const files = [...new Bun.Glob("**/*.svg").scanSync({ cwd: publicDir, onlyFiles: true })].sort();
  for (const file of files) {
    const source = await Bun.file(join(publicDir, file)).text();
    const minified = minifySvg(source, file);
    await Bun.write(join(outputDir, file), minified);
    stats.files++;
    stats.bytesBefore += Buffer.byteLength(source);
    stats.bytesAfter += Buffer.byteLength(minified);
  }
  return stats;
}

/** Only explicitly declared, unescaped, non-interpolated HTML constants. */
export async function minifyHtmlTemplateConstant(source: string, name: string): Promise<string> {
  if (!/^[A-Za-z_$][\w$]*$/.test(name)) throw new Error(`Invalid HTML template constant '${name}'`);
  const escapedName = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const pattern = new RegExp(`\\bconst\\s+${escapedName}\\s*=\\s*\x60([^\x60]*)\x60\\s*;`);
  const match = pattern.exec(source);
  if (!match || /\\|\$\{/.test(match[1])) {
    throw new Error(`HTML template '${name}' must be a static, unescaped template literal`);
  }
  const html = await minifyHtml(match[1], `${name}.html`);
  return source.slice(0, match.index) + `const ${name} = ${JSON.stringify(html)};` + source.slice(match.index + match[0].length);
}

export interface MinificationStats {
  files: number;
  bytesBefore: number;
  bytesAfter: number;
}

/** Final pass for all build modes, after plugins and before publishing staging. */
export async function minifyHtmlFiles(directory: string): Promise<MinificationStats> {
  const stats = { files: 0, bytesBefore: 0, bytesAfter: 0 };
  const files = [...new Bun.Glob("**/*.html").scanSync({ cwd: directory, onlyFiles: true })].sort();
  for (const file of files) {
    const path = join(directory, file);
    const source = await Bun.file(path).text();
    const minified = await minifyHtml(source, file);
    await Bun.write(path, minified);
    stats.files++;
    stats.bytesBefore += Buffer.byteLength(source);
    stats.bytesAfter += Buffer.byteLength(minified);
  }
  return stats;
}
